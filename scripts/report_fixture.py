#!/usr/bin/env python3
"""Embed the exact Markdown in Solidity so forge tests need no filesystem permission.

Standard library only. --check compares the committed fixture with the report;
without it, regenerate the fixture after an editorial change.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "report.md"
FIXTURE = ROOT / "test" / "fixtures" / "ReportText.sol"


def render(report: str) -> str:
    # json string escaping is suitable for these Unicode Solidity literals.
    chunks = ["            unicode" + json.dumps(line, ensure_ascii=False)
              for line in report.splitlines(keepends=True)]
    return (
        "// SPDX-License-Identifier: MIT\n"
        "pragma solidity 0.8.26;\n\n"
        "// Generated by scripts/report_fixture.py; edit report.md instead.\n"
        f"// SHA-256 of report.md: {hashlib.sha256(report.encode()).hexdigest()}\n"
        "library ReportText {\n"
        "    function text() internal pure returns (string memory) {\n"
        "        return string.concat(\n"
        + ",\n".join(chunks)
        + "\n        );\n    }\n}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    report = REPORT.read_text(encoding="utf-8")
    expected = render(report)
    if args.check:
        if not FIXTURE.exists() or FIXTURE.read_text(encoding="utf-8") != expected:
            print("FAIL: report fixture is stale; run python3 scripts/report_fixture.py", file=sys.stderr)
            return 1
        print(f"Fixture matches report.md ({len(report.split())} conservative words).")
    else:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(expected, encoding="utf-8")
        print(f"Generated {FIXTURE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
